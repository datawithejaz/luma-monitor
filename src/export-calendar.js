"use strict";

/**
 * Export events you're registered for on Lu.ma as a .ics file, and optionally
 * email it so you can add it to Outlook / Teams.
 *
 * Prefer Lu.ma's native live iCal subscription when your work Outlook allows
 * external calendar feeds — see README. This script is the fallback: a
 * one-shot .ics attachment that never gets committed to the (public) repo.
 *
 *   LUMA_AUTH_COOKIE='...' node export-calendar.js
 *   LUMA_AUTH_COOKIE='...' GMAIL_USER=... GMAIL_APP_PASSWORD=... NOTIFY_EMAIL=... \
 *     node export-calendar.js --email
 */

const fs = require("fs");
const path = require("path");
const os = require("os");
const nodemailer = require("nodemailer");
const { buildCalendar } = require("./ics");
const { fetchMyEvents, isUpcomingOrRecent } = require("./my-events");

const DEFAULT_OUT = path.join(os.tmpdir(), "my-luma-events.ics");

function parseArgs(argv) {
  const args = {
    email: false,
    out: process.env.ICS_OUT_PATH || DEFAULT_OUT,
    includePast: false,
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--email") args.email = true;
    else if (a === "--include-past") args.includePast = true;
    else if (a === "--out" && argv[i + 1]) {
      args.out = argv[++i];
    } else if (a === "--help" || a === "-h") {
      args.help = true;
    }
  }
  return args;
}

function emailConfigured() {
  return Boolean(
    process.env.GMAIL_USER && process.env.GMAIL_APP_PASSWORD && process.env.NOTIFY_EMAIL
  );
}

function formatScheduleLine(event) {
  const start = event.start_at
    ? new Date(event.start_at).toLocaleString("en-GB", {
        timeZone: event.timezone || "Europe/London",
        weekday: "short",
        day: "numeric",
        month: "short",
        hour: "2-digit",
        minute: "2-digit",
      })
    : "TBC";
  const status = event.approval_status ? ` [${event.approval_status}]` : "";
  const venue = event.venue ? ` — ${event.venue}` : "";
  return `• ${start}${status} — ${event.name}${venue}`;
}

async function emailIcs({ icsBody, events, outPath }) {
  if (!emailConfigured()) {
    throw new Error(
      "Email not configured — set GMAIL_USER, GMAIL_APP_PASSWORD and NOTIFY_EMAIL."
    );
  }

  const transporter = nodemailer.createTransport({
    service: "gmail",
    auth: { user: process.env.GMAIL_USER, pass: process.env.GMAIL_APP_PASSWORD },
  });

  const list = events.map(formatScheduleLine).join("\n") || "(none)";
  const text = [
    `Your upcoming Lu.ma events (${events.length}).`,
    "",
    "Attach the .ics to your work Outlook / Teams calendar:",
    "  Outlook web → Calendar → Add calendar → Upload from file",
    "  Or open the attachment on your phone and tap Add to Calendar.",
    "",
    "Better long-term (live sync): Lu.ma Settings → Calendar Syncing →",
    "Add iCal Subscription → Outlook. That feed updates as you RSVP.",
    "Docs: https://help.luma.com/p/ical-syncing",
    "",
    "Events in this file:",
    list,
    "",
    "---",
    "Generated by luma-monitor export-calendar.js",
  ].join("\n");

  const info = await transporter.sendMail({
    from: `"Luma Monitor" <${process.env.GMAIL_USER}>`,
    to: process.env.NOTIFY_EMAIL,
    subject: `📅 My Luma events (.ics) — ${events.length} upcoming`,
    text,
    attachments: [
      {
        filename: path.basename(outPath) || "my-luma-events.ics",
        content: icsBody,
        contentType: "text/calendar; charset=utf-8; method=PUBLISH",
      },
    ],
  });

  const accepted = info?.accepted?.length ?? 0;
  const rejected = info?.rejected?.length ?? 0;
  const response = info?.response || "no response";
  if (accepted === 0) {
    throw new Error(
      `Email NOT accepted — ${rejected} recipient(s) rejected. SMTP said: ${response}`
    );
  }
  console.log(
    `✅ .ics emailed — ${events.length} event(s) ` +
      `[SMTP accepted ${accepted}, rejected ${rejected}: ${response}]`
  );
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    console.log(`Usage: node export-calendar.js [--email] [--out PATH] [--include-past]

Fetches events you're registered for / hosting on Lu.ma and writes a .ics file.
With --email, also attaches it to NOTIFY_EMAIL (never commits the file).

Prefer Lu.ma's live Outlook iCal subscription when your org allows it:
  https://lu.ma/settings → Calendar Syncing → Add iCal Subscription → Outlook`);
    return;
  }

  console.log("Fetching your Lu.ma registrations…");
  const { events: all, sourceUrl } = await fetchMyEvents();
  console.log(`Source: ${sourceUrl}`);
  console.log(`Raw entries with ids: ${all.length}`);

  const events = args.includePast ? all : all.filter((e) => isUpcomingOrRecent(e));
  events.sort((a, b) => new Date(a.start_at) - new Date(b.start_at));

  console.log(`Including in .ics: ${events.length}`);
  events.forEach((e) => console.log(`   ${formatScheduleLine(e)}`));

  const icsBody = buildCalendar(events);
  fs.writeFileSync(args.out, icsBody, "utf8");
  console.log(`Wrote ${args.out} (${Buffer.byteLength(icsBody)} bytes)`);

  // Mirror into GITHUB_STEP_SUMMARY when running in Actions (no event names of
  // other people — only your own registrations, which the owner already knows).
  if (process.env.GITHUB_STEP_SUMMARY) {
    const summary = [
      "### My Lu.ma calendar export",
      "",
      `Wrote \`.ics\` with **${events.length}** upcoming event(s).`,
      args.email
        ? "Emailed as an attachment to `NOTIFY_EMAIL`."
        : "Email skipped (pass `--email` / set `EMAIL_ICS=1`).",
      "",
      "Prefer live sync when possible: [Lu.ma iCal Syncing](https://help.luma.com/p/ical-syncing).",
      "",
    ].join("\n");
    fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY, summary);
  }

  const shouldEmail = args.email || process.env.EMAIL_ICS === "1";
  if (shouldEmail) {
    await emailIcs({ icsBody, events, outPath: args.out });
  } else {
    console.log("Tip: re-run with --email to attach the .ics to NOTIFY_EMAIL.");
  }
}

if (require.main === module) {
  main().catch((err) => {
    console.error("Fatal:", err.message);
    process.exit(1);
  });
}

module.exports = { parseArgs, emailConfigured };
